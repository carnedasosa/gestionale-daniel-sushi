import { afterEach, expect, it, vi } from 'vitest'
const m = vi.hoisted(() => ({ postgres: vi.fn(),unsafe: vi.fn(),reserve: vi.fn(),release: vi.fn(),begin: vi.fn() }))
vi.mock('server-only',() => ({}))
vi.mock('postgres',() => ({ default: m.postgres }))
afterEach(() => { vi.unstubAllEnvs(); vi.resetModules(); vi.resetAllMocks() })
it('riserva una connessione per ogni lettura parallela e conserva i parametri', async () => {
  vi.stubEnv('DATABASE_URL','postgres://prova')
  m.postgres.mockReturnValue({ unsafe: m.unsafe,reserve: m.reserve })
  m.reserve.mockResolvedValue({ unsafe: m.unsafe,release: m.release })
  m.unsafe.mockResolvedValueOnce([{ a: 1 }]).mockResolvedValueOnce([{ b: 2 }])
  const { db } = await import('./db')
  expect(await Promise.all([db.query('select 1 as a'),db.query('select $1 as b',[2])])).toEqual([[{ a: 1 }],[{ b: 2 }]])
  expect(m.postgres).toHaveBeenCalledWith('postgres://prova',{ prepare: false,max: 5 })
  expect(m.reserve).toHaveBeenCalledTimes(2)
  expect(m.release).toHaveBeenCalledTimes(2)
  expect(m.unsafe).toHaveBeenNthCalledWith(1,'select 1 as a',[])
  expect(m.unsafe).toHaveBeenNthCalledWith(2,'select $1 as b',[2])
})
it('restituisce la connessione al pool anche quando la query fallisce', async () => {
  vi.stubEnv('DATABASE_URL','postgres://prova')
  m.postgres.mockReturnValue({ unsafe: m.unsafe,reserve: m.reserve })
  m.reserve.mockResolvedValue({ unsafe: m.unsafe,release: m.release })
  m.unsafe.mockRejectedValueOnce(new Error('lettura fallita'))
  const { db } = await import('./db')
  await expect(db.query('select 1')).rejects.toThrow('lettura fallita')
  expect(m.release).toHaveBeenCalledOnce()
})
it('le transazioni usano begin e la connessione assegnata al callback', async () => {
  vi.stubEnv('DATABASE_URL','postgres://prova')
  m.postgres.mockReturnValue({ begin: m.begin,reserve: m.reserve })
  m.begin.mockImplementation(fn => fn({ unsafe: m.unsafe }))
  m.unsafe.mockResolvedValueOnce([{ valore: 1 }])
  const { db } = await import('./db')
  expect(await db.transazione(tx => tx.query('select $1 as valore',[1]))).toEqual([{ valore: 1 }])
  expect(m.begin).toHaveBeenCalledOnce(); expect(m.reserve).not.toHaveBeenCalled()
})
